# 이 플러그인의 계약. 모든 검사가 이것을 지킨다.
#
#   숫자를 낼 때는 못 센 것을 함께 낸다.
#
# 0은 "없다"와 "못 셌다" 둘 다일 수 있다. git log는 없는 경로에도,
# 추적하지 않는 파일에도 오류 없이 빈 출력을 낸다. sed는 절 제목이
# 다르면 아무것도 못 뽑고도 조용하다. 그 0을 "없음"으로 보고하면
# 가장 급히 봐야 할 것이 가장 안전해 보인다.
#
# 그래서 셋을 함께 낸다: 센 것 · 못 센 것 · 왜 못 셌는지.

# counted <값> <단위> [분모]
#   센 결과 한 줄. 분모를 주면 "N/M" 으로 낸다.
counted() {
  if [ -n "${3:-}" ]; then echo "    $1/$3 $2"; else echo "    $1$2"; fi
}

# uncounted <개수> <왜>
#   못 센 것이 있으면 반드시 이 줄을 낸다. 없으면 아무것도 안 낸다.
uncounted() {
  [ "${1:-0}" -gt 0 ] || return 0
  echo "    못 셈 $1건 — $2"
  echo "    (이 수만큼은 '없음'이 아니라 '모름'이다)"
}

# verdict <센것> <못센것> <단위>
#   마지막 한 줄. 못 센 것이 있으면 단정하지 않는다.
verdict() {
  if [ "${2:-0}" -gt 0 ]; then
    echo "  → $1$3 확인, $2건은 못 셈. 이 결과로 '없다'고 말하지 않는다."
  else
    echo "  → $1$3"
  fi
}

# empty_means <무엇> <확인방법>
#   0이 나왔을 때 그게 진짜인지 확인하라고 알린다.
empty_means() {
  echo "    0건이다. 진짜 없는 것인지 확인하려면: $2"
}
